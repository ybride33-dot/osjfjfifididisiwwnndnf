// Exercises the actual backup functions with a simulated browser localStorage.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync(path.join(__dirname, '..', 'index.html'), 'utf8');
const begin = html.indexOf('function makeFullBackup(){');
const end = html.indexOf('function closePanel()', begin);
if (begin < 0 || end < 0) throw new Error('Backup functions not found');
let data = new Map([['jvs-state','{"xp":42,"facts":["test"]}'], ['jvs-trace','[{"q":"hi"}]'], ['jvs-gk','secret-test-only']]);
const storage = {get length(){return data.size}, key:i=>[...data.keys()][i]??null, getItem:k=>data.has(k)?data.get(k):null, setItem:(k,v)=>data.set(k,String(v))};
let legacy;
const ctx = vm.createContext({localStorage:storage, toast:()=>{}, setTimeout:()=>{}, location:{reload(){}}, store:{set:(k,v)=>{legacy=[k,v]}}});
vm.runInContext(html.slice(begin,end),ctx);
const backup = ctx.makeFullBackup();
assert.equal(backup.v,2);
assert.equal(backup.keys['jvs-state'],data.get('jvs-state'));
assert.equal(backup.keys['jvs-trace'],data.get('jvs-trace'));
assert.equal(Object.hasOwn(backup.keys,'jvs-gk'),false);
assert.equal(JSON.stringify(backup).includes('secret-test-only'),false);
const json=JSON.stringify(backup);
data = new Map([['jvs-gk','new-local-secret']]);
assert.equal(ctx.applyBackup(json),true);
assert.equal(data.get('jvs-state'),'{"xp":42,"facts":["test"]}');
assert.equal(data.get('jvs-trace'),'[{"q":"hi"}]');
assert.equal(data.get('jvs-gk'),'new-local-secret');
assert.equal(ctx.applyBackup(JSON.stringify({v:2,keys:{'jvs-gk':'bad'}})),true);
assert.equal(data.get('jvs-gk'),'new-local-secret');
assert.equal(ctx.applyBackup('{bad'),false);
assert.equal(ctx.applyBackup(JSON.stringify({xp:5})),true);
assert.equal(legacy[0],'jvs-state'); assert.equal(legacy[1].xp,5);
console.log('PASS backup export, secret exclusion, restore, legacy and malformed input (mock storage)');
